#!/usr/bin/env python3
"""
Run PEER for HTAN ASC/SSC disease-specific pseudobulk expression.

Unlike the legacy script, this version does NOT use the N103 covariate file.
It uses the cell-specific covariate/sample mapping generated by:
  08_match_HTAN_ASC_SSC_expression_genotype_HTANdirect.py

Known covariates are detected dynamically:
  Age
  Sex
  all segment_* dummy columns present in the cell-specific covariate file
  PC1-PC5

The expression matrix must already be TPM/log2/QN/INV processed.\nPEER residual outputs are relabeled from ENSG(.version) to GENCODE gene symbols.
"""

import argparse
import subprocess
from pathlib import Path
import numpy as np
import pandas as pd
import re

N_ITERATIONS = 1000
EXPRESSION_ROOT = Path(
    "/v5000/data/l2_bioinfo1/liq17/scTWAS/data/VUMC_HTAN/"
    "expression/ADSER_pseudobulk_expression_for_peer"
)
ID_COL = "expression_id"
GENO_ID_COL = "genotype_id"

# GENCODE annotation used to convert ENSG(.version) -> gene symbol in outputs.
DEFAULT_GTF = Path(
    "/v5000/data/l2_bioinfo1/liq17/LQ_references/gencode/gencode.v26.annotation.gtf"
)


def load_ensg_to_symbol(gtf_file: Path):
    """
    Read GENCODE gene records and return ENSG-without-version -> gene_name.

    Only `gene` feature rows are parsed. This keeps the mapping lightweight and
    avoids transcript-level duplicates.
    """
    if not gtf_file.exists():
        raise FileNotFoundError(f"GENCODE GTF not found: {gtf_file}")

    mapping = {}
    conflicting = {}

    gene_id_re = re.compile(r'gene_id "([^"]+)"')
    gene_name_re = re.compile(r'gene_name "([^"]+)"')

    with gtf_file.open("r") as fh:
        for line in fh:
            if not line or line.startswith("#"):
                continue
            fields = line.rstrip("\n").split("\t")
            if len(fields) < 9 or fields[2] != "gene":
                continue

            attrs = fields[8]
            m_id = gene_id_re.search(attrs)
            m_name = gene_name_re.search(attrs)
            if m_id is None or m_name is None:
                continue

            gene_id = m_id.group(1)
            gene_base = re.sub(r"\.\d+$", "", gene_id)
            gene_name = m_name.group(1)

            if gene_base in mapping and mapping[gene_base] != gene_name:
                conflicting.setdefault(gene_base, set()).update(
                    [mapping[gene_base], gene_name]
                )
            else:
                mapping[gene_base] = gene_name

    if conflicting:
        examples = "; ".join(
            f"{g}={','.join(sorted(v))}"
            for g, v in list(conflicting.items())[:10]
        )
        raise ValueError(
            "Conflicting ENSG-to-gene_name mappings found in GTF. "
            f"Examples: {examples}"
        )

    if not mapping:
        raise ValueError(f"No gene_id/gene_name mappings parsed from: {gtf_file}")

    return mapping


def map_genes_to_symbols(genes, ensg_to_symbol):
    """
    Convert ENSG(.version) identifiers to GENCODE gene_name.

    Existing non-ENSG identifiers are retained unchanged. Mapping must produce
    unique output identifiers, because downstream expression matrices require
    one phenotype row per gene.
    """
    symbols = []
    unmapped_ensg = []

    for gene in map(str, genes):
        gene_base = re.sub(r"\.\d+$", "", gene)
        if re.match(r"^ENSG\d+$", gene_base):
            symbol = ensg_to_symbol.get(gene_base)
            if symbol is None or symbol == "":
                unmapped_ensg.append(gene)
                symbols.append(None)
            else:
                symbols.append(symbol)
        else:
            # Already a symbol/other identifier.
            symbols.append(gene)

    if unmapped_ensg:
        raise ValueError(
            f"{len(unmapped_ensg)} ENSG genes could not be mapped to a GENCODE "
            "gene symbol. Examples: " + ", ".join(unmapped_ensg[:20])
        )

    dup_mask = pd.Series(symbols).duplicated(keep=False)
    if dup_mask.any():
        dup_symbols = sorted(set(pd.Series(symbols)[dup_mask].astype(str)))
        raise ValueError(
            "ENSG-to-symbol conversion produced duplicated gene symbols. "
            "Stopping rather than silently dropping/merging genes. Examples: "
            + ", ".join(dup_symbols[:20])
        )

    return list(map(str, symbols))


def peer_factor_count(n_samples: int) -> int:
    if n_samples < 150:
        return 15
    elif n_samples < 250:
        return 30
    elif n_samples < 350:
        return 45
    return 60


def orient_residuals(raw, genes, samples):
    g, n = len(genes), len(samples)
    if raw.shape == (g, n):
        out = raw.copy()
    elif raw.shape == (n, g):
        out = raw.T
    else:
        raise ValueError(
            f"Unexpected residuals.csv shape {raw.shape}; expected {(g, n)} or {(n, g)}."
        )
    out.index = genes
    out.columns = samples
    out.index.name = "gene"
    return out


def orient_x(raw, samples, covariates, n_peer):
    n = len(samples)
    if raw.shape[0] == n:
        x = raw.copy()
    elif raw.shape[1] == n:
        x = raw.T
    else:
        return raw
    x.index = samples
    x.index.name = ID_COL
    k = x.shape[1]
    if k == n_peer:
        x.columns = [f"PEER{i+1}" for i in range(n_peer)]
    elif k == len(covariates) + n_peer:
        x.columns = list(covariates) + [f"PEER{i+1}" for i in range(n_peer)]
    else:
        x.columns = [f"Factor{i+1}" for i in range(k)]
    return x


def orient_w(raw, genes):
    g = len(genes)
    if raw.shape[0] == g:
        w = raw.copy()
    elif raw.shape[1] == g:
        w = raw.T
    else:
        return raw
    w.index = genes
    w.index.name = "gene"
    w.columns = [f"Loading{i+1}" for i in range(w.shape[1])]
    return w


parser = argparse.ArgumentParser()
parser.add_argument(
    "cell_type",
    choices=["ASC", "SSC", "ABS", "EE", "GOB", "CT", "TUF", "TAC", "STM"],
)
parser.add_argument("--expression-root", default=str(EXPRESSION_ROOT))
parser.add_argument("--iterations", type=int, default=N_ITERATIONS)
parser.add_argument("--expression-file", default=None)
parser.add_argument("--cov-file", default=None)
parser.add_argument(
    "--gtf",
    default=str(DEFAULT_GTF),
    help="GENCODE GTF used to map ENSG(.version) to gene symbols in PEER outputs.",
)
args = parser.parse_args()

cell_type = args.cell_type.upper()
CELL_DIR = Path(args.expression_root) / cell_type

if args.expression_file:
    EXPR_FILE = Path(args.expression_file)
else:
    lower = CELL_DIR / f"pseudobulk_counts_{cell_type}.tpmlog2.qc.qn.rmlowcounts.inv.csv"
    upper = CELL_DIR / f"pseudobulk_counts_{cell_type}.tpmlog2.qc.qn.rmlowcounts.INV.csv"
    EXPR_FILE = lower if lower.exists() else upper

COV_FILE = Path(args.cov_file) if args.cov_file else CELL_DIR / f"{cell_type}.age_sex_tissue_geno5PCs.csv"
GTF_FILE = Path(args.gtf)
OUT_DIR = CELL_DIR / f"PEER_{cell_type}"
OUT_DIR.mkdir(parents=True, exist_ok=True)
PREFIX = f"pseudobulk_counts_{cell_type}.tpmlog2.qc.qn.rmlowcounts.inv"

if not EXPR_FILE.exists():
    raise FileNotFoundError(f"Expression file not found: {EXPR_FILE}")
if not COV_FILE.exists():
    raise FileNotFoundError(f"Cell-specific covariate file not found: {COV_FILE}")
if not GTF_FILE.exists():
    raise FileNotFoundError(f"GENCODE GTF not found: {GTF_FILE}")

print("=" * 78)
print(f"PEER: HTAN {cell_type} direct-genotype model")
print("=" * 78)
print(f"Expression  : {EXPR_FILE}")
print(f"Covariates  : {COV_FILE}")
print(f"GENCODE GTF : {GTF_FILE}")
print(f"Output      : {OUT_DIR}")

expr = pd.read_csv(EXPR_FILE)
if "gene" not in expr.columns:
    raise ValueError("Expression file must contain first column named 'gene'.")
expr["gene"] = expr["gene"].astype(str)
if expr["gene"].duplicated().any():
    raise ValueError("Duplicated genes in PEER expression input.")
expr = expr.set_index("gene")
expr.columns = expr.columns.astype(str)
expr = expr.apply(pd.to_numeric, errors="raise")
if not np.isfinite(expr.to_numpy(dtype=float)).all():
    raise ValueError("Expression matrix contains NaN/Inf.")

# Keep the original ENSG identifiers internally for PEER. Build a parallel,
# order-preserving gene-symbol vector used only when labeling outputs.
genes_input = expr.index.astype(str).tolist()
ensg_to_symbol = load_ensg_to_symbol(GTF_FILE)
gene_symbols = map_genes_to_symbols(genes_input, ensg_to_symbol)
gene_symbol_by_input = dict(zip(genes_input, gene_symbols))

gene_map = pd.DataFrame(
    {
        "input_gene": genes_input,
        "ENSG_no_version": [
            re.sub(r"\.\d+$", "", g) if re.match(r"^ENSG\d+", g) else ""
            for g in genes_input
        ],
        "gene_symbol": gene_symbols,
    }
)
gene_map.to_csv(
    OUT_DIR / f"{cell_type}.PEER_gene_ENSG_to_symbol_map.csv",
    index=False,
)
print(f"Gene symbols mapped : {len(gene_symbols):,}/{len(genes_input):,}")

cov_all = pd.read_csv(COV_FILE)
required_base = {ID_COL, GENO_ID_COL, "Age", "Sex", "PC1", "PC2", "PC3", "PC4", "PC5"}
missing = required_base.difference(cov_all.columns)
if missing:
    raise ValueError("Missing covariate columns: " + ", ".join(sorted(missing)))

cov_all[ID_COL] = cov_all[ID_COL].astype(str)
cov_all[GENO_ID_COL] = cov_all[GENO_ID_COL].astype(str)
if cov_all[ID_COL].duplicated().any():
    raise ValueError(f"Duplicated {ID_COL} in covariate file.")
if cov_all[GENO_ID_COL].duplicated().any():
    raise ValueError(f"Duplicated {GENO_ID_COL} in covariate file.")

segment_cols = sorted([c for c in cov_all.columns if c.startswith("segment_")])
COVARIATE_COLS = ["Age", "Sex", *segment_cols, "PC1", "PC2", "PC3", "PC4", "PC5"]

print(f"Expression genes    : {expr.shape[0]:,}")
print(f"Expression samples  : {expr.shape[1]:,}")
print(f"Covariate rows      : {cov_all.shape[0]:,}")
print(f"Known covariates    : {', '.join(COVARIATE_COLS)}")

cov_all = cov_all.set_index(ID_COL)
expr_samples = expr.columns.tolist()
expr_set = set(expr_samples)
common_samples = [s for s in cov_all.index if s in expr_set]
expr_only = [s for s in expr_samples if s not in set(cov_all.index)]
cov_only = [s for s in cov_all.index if s not in expr_set]

print(f"Matched samples     : {len(common_samples):,}")
print(f"Expression only     : {len(expr_only):,}")
print(f"Covariate only      : {len(cov_only):,}")

pd.Series(expr_only, name=ID_COL).to_csv(OUT_DIR / f"{cell_type}.expression_only_samples.csv", index=False)
pd.Series(cov_only, name=ID_COL).to_csv(OUT_DIR / f"{cell_type}.covariate_only_samples.csv", index=False)

if not common_samples:
    raise RuntimeError("No overlapping expression_id values between expression and covariates.")

expr_common = expr.loc[:, common_samples].copy()
genotype_ids = cov_all.loc[common_samples, GENO_ID_COL].astype(str).tolist()
if len(set(genotype_ids)) != len(genotype_ids):
    raise RuntimeError("Matched genotype_id values are not unique.")

MATCHED_EXPR_EXPRID_FILE = CELL_DIR / f"{PREFIX}.N{len(common_samples)}.matched.expression_id.geno_order.csv"
MATCHED_EXPR_GENOID_FILE = CELL_DIR / f"{PREFIX}.N{len(common_samples)}.matched.genotype_id.geno_order.csv"
expr_common.to_csv(MATCHED_EXPR_EXPRID_FILE)
expr_common_genoid = expr_common.copy()
expr_common_genoid.columns = genotype_ids
expr_common_genoid.to_csv(MATCHED_EXPR_GENOID_FILE)

sample_map = pd.DataFrame({ID_COL: common_samples, GENO_ID_COL: genotype_ids})
sample_map.to_csv(OUT_DIR / f"{cell_type}.matched_expression_genotype_sample_map.csv", index=False)

cov_common = cov_all.loc[common_samples, COVARIATE_COLS].copy().apply(pd.to_numeric, errors="raise")
if cov_common.isna().any().any():
    bad = cov_common.columns[cov_common.isna().any()].tolist()
    raise ValueError(f"Missing covariate values detected in: {bad}")
if not np.isfinite(cov_common.to_numpy(dtype=float)).all():
    raise ValueError("Covariates contain NaN/Inf.")

expr_NxG = expr_common.T
if expr_NxG.index.tolist() != cov_common.index.tolist():
    raise RuntimeError("Expression/covariate sample order mismatch after matching.")

n_samples = expr_NxG.shape[0]
n_genes = expr_NxG.shape[1]
n_peer = peer_factor_count(n_samples)
print(f"PEER samples        : {n_samples}")
print(f"PEER genes          : {n_genes}")
print(f"PEER factors        : {n_peer}")
print(f"PEER iterations     : {args.iterations}")

PEER_EXPR_FILE = OUT_DIR / f"{PREFIX}.peertool.expression.csv"
PEER_COV_FILE = OUT_DIR / f"{cell_type}.age_sex_tissue_geno5PCs.peertool.covariates.csv"
expr_NxG.to_csv(PEER_EXPR_FILE, index=False, header=False)
cov_common.to_csv(PEER_COV_FILE, index=False, header=False)
expr_NxG.to_csv(OUT_DIR / f"{PREFIX}.peertool.expression.labeled.csv")
cov_all.loc[common_samples].reset_index().to_csv(
    OUT_DIR / f"{cell_type}.age_sex_tissue_geno5PCs.matched.labeled.csv", index=False
)
sample_map.to_csv(OUT_DIR / f"{cell_type}.PEER_samples.csv", index=False)
peer_gene_table = pd.DataFrame(
    {
        "gene": [gene_symbol_by_input[g] for g in expr_NxG.columns],
        "ENSG": list(expr_NxG.columns),
    }
)
peer_gene_table.to_csv(
    OUT_DIR / f"{cell_type}.PEER_genes.csv",
    index=False,
)

PEER_OUT_DIR = OUT_DIR / "PEER_outputs"
PEER_OUT_DIR.mkdir(parents=True, exist_ok=True)
peer_cmd = [
    "peertool", "-f", str(PEER_EXPR_FILE), "-c", str(PEER_COV_FILE),
    "-n", str(n_peer), "-i", str(args.iterations), "-o", str(PEER_OUT_DIR),
]
print("Running:")
print(" ".join(peer_cmd))
subprocess.run(peer_cmd, check=True)

genes = expr_NxG.columns.tolist()
samples = expr_NxG.index.tolist()
residuals_file = PEER_OUT_DIR / "residuals.csv"
x_file = PEER_OUT_DIR / "X.csv"
w_file = PEER_OUT_DIR / "W.csv"

if residuals_file.exists():
    resid_raw = pd.read_csv(residuals_file, header=None)
    resid = orient_residuals(resid_raw, genes, samples)

    # Change only the output row labels: ENSG(.version) -> gene symbol.
    # PEER itself was run in the original gene order, so residual values/order
    # are unchanged.
    residual_gene_symbols = [gene_symbol_by_input[g] for g in genes]
    resid.index = residual_gene_symbols
    resid.index.name = "gene"

    if resid.index.duplicated().any():
        dup = resid.index[resid.index.duplicated(keep=False)].unique().tolist()
        raise RuntimeError(
            "Duplicated gene symbols detected immediately before residual output: "
            + ", ".join(map(str, dup[:20]))
        )

    out_exprid = OUT_DIR / f"{PREFIX}.PEER_residuals.expression_id.csv.gz"
    resid.to_csv(out_exprid, compression="gzip")

    resid_genoid = resid.copy()
    resid_genoid.columns = genotype_ids
    out_genoid = OUT_DIR / f"{PREFIX}.PEER_residuals.genotype_id.csv.gz"
    resid_genoid.to_csv(out_genoid, compression="gzip")

    print(f"Residual gene IDs   : HGNC/GENCODE gene symbols")
    print(f"Residuals           : {out_exprid}")
    print(f"Genotype-ID version : {out_genoid}")
else:
    print(f"WARNING: residuals.csv not found: {residuals_file}")

if x_file.exists():
    x = orient_x(pd.read_csv(x_file, header=None), samples, COVARIATE_COLS, n_peer)
    x.to_csv(OUT_DIR / f"{cell_type}.PEER_X.labeled.csv")

if w_file.exists():
    w = orient_w(pd.read_csv(w_file, header=None), genes)
    if w.shape[0] == len(genes):
        w.index = [gene_symbol_by_input[g] for g in genes]
        w.index.name = "gene"
    w.to_csv(OUT_DIR / f"{cell_type}.PEER_W.labeled.csv")

summary = OUT_DIR / f"{cell_type}.PEER_summary.txt"
with open(summary, "w") as fh:
    fh.write("project=HTAN_direct\n")
    fh.write(f"cell_type={cell_type}\n")
    fh.write(f"expression_file={EXPR_FILE}\n")
    fh.write(f"covariate_file={COV_FILE}\n")
    fh.write(f"gencode_gtf={GTF_FILE}\n")
    fh.write("residual_gene_identifier=gene_symbol\n")
    fh.write("legacy_N103_restriction=False\n")
    fh.write(f"n_expression_genes={expr.shape[0]}\n")
    fh.write(f"n_expression_samples={expr.shape[1]}\n")
    fh.write(f"n_common_samples={len(common_samples)}\n")
    fh.write(f"covariates={','.join(COVARIATE_COLS)}\n")
    fh.write(f"n_peer_factors={n_peer}\n")
    fh.write(f"n_iterations={args.iterations}\n")

print("=" * 78)
print("DONE")
print("=" * 78)
print(f"Cell type : {cell_type}")
print(f"Samples   : {len(common_samples)}")
print(f"Output    : {OUT_DIR}")
print(f"Summary   : {summary}")
