            quote = FALSE,
            col.names = FALSE,
            row.names = FALSE,
            sep = "\t"
          )
          do_covariance(
            gene, cis_gt, weighted_snps_info$SNP,
            weighted_snps_info$varID, covariance_file
          )
        }
      }
    }

    print(model_summary)
    write(model_summary, file = model_summary_file, append = TRUE, ncol = 14, sep = "\t")
  }, error = function(e) {
