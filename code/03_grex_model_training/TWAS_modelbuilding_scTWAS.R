for (i in 1:n_genes) {
  cat(i, "/", n_genes, "\n")
  gene <- genes[i]
  gene_name <- as.character(gene_annot$genename[gene_annot$geneid == gene])
  model_summary <- c(gene, gene_name, alpha, NA, NA, NA, 0, NA, NA, NA, NA, NA, NA, NA)
  coords <- get_gene_coords(gene_annot, gene)
  cis_gt <- get_cis_genotype_varID_local(gt_df, snp_annot, "pos", coords, cis_window)

  tryCatch({
    if (ncol(cis_gt) >= min_cis_snps) {
      adj_expression <- as.numeric(expr_df_match_gt[[i]])

      if (length(adj_expression) != nrow(cis_gt)) {
        stop(
          "Pre-glmnet sample mismatch for ", gene,
          ": expression=", length(adj_expression),
          ", genotype=", nrow(cis_gt)
        )
      }

      elnet_out <- do_elastic_net(
        cis_gt,
        adj_expression,
        effective_n_folds,
        cv_fold_ids,
        n_times,
        alpha
      )

      if (length(elnet_out) > 0) {
        eval <- evaluate_performance(
          cis_gt, adj_expression, elnet_out$cv_fit,
          elnet_out$best_lam_ind, elnet_out$best_lambda,
          cv_fold_ids, effective_n_folds
        )

        model_summary <- c(
          gene, as.character(gene_name), alpha, elnet_out$min_avg_cvm,
          elnet_out$best_lam_ind, elnet_out$best_lambda, eval$n_weights,
          eval$R2_mean, eval$R2_sd, eval$inR2, eval$pred_perf_rsq,
          eval$pred_perf_pval, eval$R2_global, eval$r_squared_global
        )

        if (eval$n_weights > 0) {
          weighted_snps_info <- snp_annot %>%
            filter(varID %in% eval$weighted_snps) %>%
            select(SNP, varID, ref, effect)

          if (nrow(weighted_snps_info) == 0) {
            stop("No weighted SNPs matched snp_annot for gene ", gene)
          }

          weighted_snps_info$gene <- gene
          weighted_snps_info <- weighted_snps_info %>%
            merge(data.frame(weights = eval$weights, varID = eval$weighted_snps), by = "varID") %>%
            select(gene, SNP, varID, ref, effect, weights)

          write.table(
            weighted_snps_info,
