      "Gene ", gene, " failed: ", conditionMessage(e),
      " [expression_n=", nrow(expr_df_match_gt),
      ", cis_gt_n=", if (exists("cis_gt")) nrow(cis_gt) else NA_integer_,
      ", cis_snps=", if (exists("cis_gt")) ncol(cis_gt) else NA_integer_,
      ", cv_fold_n=", nrow(cv_fold_ids),
      "]"
    )
  })
