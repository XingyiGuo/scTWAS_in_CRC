# -----------------------------------------------------------------------------
# PEER residual expression reader
# Input format:
#   rows    = genes
#   columns = expression samples
#   first column = gene identifier (gene symbol or ENSG ID)
# Output:
#   rows    = samples
#   columns = GENCODE gene IDs
# -----------------------------------------------------------------------------
read_peer_expression <- function(expression_file, gene_annot) {
  x <- fread(
    expression_file,
    data.table = FALSE,
    check.names = FALSE
  )

  if (ncol(x) < 2) {
    stop("Expression file must contain one gene column plus >=1 sample column.")
  }

  gene_col <- names(x)[1]
  gene_input <- trimws(as.character(x[[1]]))
  sample_ids <- names(x)[-1]

  if (anyDuplicated(sample_ids)) {
    dup <- unique(sample_ids[duplicated(sample_ids)])
    stop(
      "Expression file has duplicated sample columns: ",
      paste(head(dup, 20), collapse = ", ")
    )
  }

  if (!all(c("geneid", "genename") %in% names(gene_annot))) {
    stop("gene_annot must contain columns 'geneid' and 'genename'.")
  }

  annot_geneid <- as.character(gene_annot$geneid)
  annot_genename <- as.character(gene_annot$genename)

  # Match in priority order:
  #   1) exact GENCODE gene ID
  #   2) ENSG ID ignoring version suffix
  #   3) exact gene symbol -> GENCODE gene ID
  idx <- match(gene_input, annot_geneid)
  match_type <- ifelse(!is.na(idx), "geneid_exact", NA_character_)

  gene_input_base <- sub("\\.\\d+$", "", gene_input)
  annot_geneid_base <- sub("\\.\\d+$", "", annot_geneid)

  need <- is.na(idx) & grepl("^ENSG[0-9]+", gene_input)
  if (any(need)) {
    idx_base <- match(gene_input_base[need], annot_geneid_base)
    idx[need] <- idx_base
    matched <- need
    matched[need] <- !is.na(idx_base)
    match_type[matched] <- "geneid_no_version"
  }

  need <- is.na(idx)
  if (any(need)) {
    idx_name <- match(gene_input[need], annot_genename)
    idx[need] <- idx_name
    matched <- need
    matched[need] <- !is.na(idx_name)
    match_type[matched] <- "gene_symbol"
  }

  mapped <- !is.na(idx)
  cat("Expression file genes      :", length(gene_input), "\n")
  cat("Genes mapped to chromosome :", sum(mapped), "\n")
  cat("  exact gene ID            :", sum(match_type == "geneid_exact", na.rm = TRUE), "\n")
  cat("  ENSG ignoring version    :", sum(match_type == "geneid_no_version", na.rm = TRUE), "\n")
  cat("  gene symbol              :", sum(match_type == "gene_symbol", na.rm = TRUE), "\n")
  cat("Genes not on chromosome    :", sum(!mapped), "\n")

  if (!any(mapped)) {
    stop(
      "No expression genes matched the chromosome-specific GENCODE annotation. ",
      "Example expression identifiers: ",
      paste(head(gene_input, 10), collapse = ", ")
    )
  }

  x <- x[mapped, , drop = FALSE]
  idx <- idx[mapped]
  gene_input_mapped <- gene_input[mapped]
  match_type_mapped <- match_type[mapped]

  canonical_geneid <- annot_geneid[idx]

  # A TWAS model must have one expression phenotype per canonical gene ID.
  # Keep the first occurrence and report any duplicates caused by aliases/versioning.
  nondup <- !duplicated(canonical_geneid)
  if (any(!nondup)) {
    cat(
      "Duplicate mapped gene IDs  :", sum(!nondup),
      "rows dropped\n"
    )
  }

  x <- x[nondup, , drop = FALSE]
  canonical_geneid <- canonical_geneid[nondup]
  gene_input_mapped <- gene_input_mapped[nondup]
  match_type_mapped <- match_type_mapped[nondup]

  expr_gene_by_sample <- as.matrix(x[, -1, drop = FALSE])
  storage.mode(expr_gene_by_sample) <- "numeric"

  if (any(!is.finite(expr_gene_by_sample))) {
    stop("Expression matrix contains NA/NaN/Inf after reading.")
  }

  # Convert genes x samples -> samples x genes.
  expr_df <- as.data.frame(
    t(expr_gene_by_sample),
    check.names = FALSE
  )
  rownames(expr_df) <- sample_ids
  colnames(expr_df) <- canonical_geneid

  if (anyDuplicated(rownames(expr_df))) {
    stop("Expression sample IDs are not unique after reading.")
  }
  if (anyDuplicated(colnames(expr_df))) {
    stop("Internal error: duplicated GENCODE gene IDs remain after mapping.")
  }

  cat("Expression matrix         :", nrow(expr_df), "samples x",
      ncol(expr_df), "genes\n")

  attr(expr_df, "gene_mapping") <- data.frame(
    input_gene = gene_input_mapped,
    geneid = canonical_geneid,
    mapping_type = match_type_mapped,
    stringsAsFactors = FALSE
  )

  expr_df
}

# -----------------------------------------------------------------------------
# Config-specific covariate/sample mapping
# -----------------------------------------------------------------------------
read_sample_mapping <- function(covariate_file, mapping_cfg) {
  cov_df <- fread(covariate_file, data.table = FALSE, check.names = FALSE)

  expr_col <- mapping_cfg$expression_id_col
  geno_col <- mapping_cfg$genotype_id_col

  required_cols <- c(expr_col, geno_col)
  missing_cols <- setdiff(required_cols, names(cov_df))
  if (length(missing_cols) > 0) {
    stop(
      "Covariate file is missing required sample-ID column(s): ",
      paste(missing_cols, collapse = ", ")
    )
  }

  map <- cov_df[, required_cols, drop = FALSE]
  names(map) <- c("expression_id", "genotype_id")
  map$expression_id <- trimws(as.character(map$expression_id))
  map$genotype_id <- trimws(as.character(map$genotype_id))

  bad <- is.na(map$expression_id) | is.na(map$genotype_id) |
         map$expression_id == "" | map$genotype_id == ""
  if (any(bad)) {
    stop("Covariate file contains missing/empty expression_id or genotype_id values.")
  }

  if (anyDuplicated(map$expression_id)) {
    dup <- unique(map$expression_id[duplicated(map$expression_id)])
    stop(
      "Covariate file has duplicated expression_id values: ",
      paste(head(dup, 20), collapse = ", ")
    )
  }

  if (anyDuplicated(map$genotype_id)) {
    dup <- unique(map$genotype_id[duplicated(map$genotype_id)])
    stop(
      "Covariate file has duplicated genotype_id values: ",
      paste(head(dup, 20), collapse = ", ")
    )
  }

  cat("Covariate rows :", nrow(map), "\n")
  map
}

rename_expression_samples <- function(expr_df, sample_map, mapping_cfg) {
  old_ids <- rownames(expr_df)
  if (is.null(old_ids)) stop("Expression matrix has no sample row names.")

  idx_expr <- match(old_ids, sample_map$expression_id)
  idx_geno <- match(old_ids, sample_map$genotype_id)

  # If an input label can be interpreted both ways but would map differently,
  # stop rather than silently assigning the wrong subject.
  ambiguous <- !is.na(idx_expr) & !is.na(idx_geno) &
    sample_map$genotype_id[idx_expr] != old_ids
  if (any(ambiguous)) {
    stop(
      "Ambiguous expression sample label(s) match both expression_id and genotype_id: ",
      paste(head(old_ids[ambiguous], 20), collapse = ", ")
    )
  }

  new_ids <- rep(NA_character_, length(old_ids))
  source_type <- rep("unmapped", length(old_ids))

  from_expr <- !is.na(idx_expr)
  new_ids[from_expr] <- sample_map$genotype_id[idx_expr[from_expr]]
  source_type[from_expr] <- "expression_id"

  already_geno <- is.na(new_ids) & !is.na(idx_geno)
  new_ids[already_geno] <- old_ids[already_geno]
  source_type[already_geno] <- "genotype_id"

  unmapped <- is.na(new_ids)
  cat("Expression samples        :", length(old_ids), "\n")
  cat("Renamed expression_id     :", sum(source_type == "expression_id"), "\n")
  cat("Already genotype_id       :", sum(source_type == "genotype_id"), "\n")
  cat("Unmapped expression sample:", sum(unmapped), "\n")

  audit <- data.frame(
    input_expression_label = old_ids,
    genotype_id = new_ids,
    mapping_type = source_type,
    stringsAsFactors = FALSE
  )

  if (any(unmapped)) {
    if (isTRUE(mapping_cfg$drop_unmapped_expression)) {
      expr_df <- expr_df[!unmapped, , drop = FALSE]
      new_ids <- new_ids[!unmapped]
    } else {
      stop(
        "Expression contains sample IDs absent from the covariate mapping. Examples: ",
        paste(head(old_ids[unmapped], 20), collapse = ", ")
      )
    }
  }

  if (length(new_ids) == 0) {
    stop("No expression samples remain after expression_id -> genotype_id mapping.")
  }
  if (anyDuplicated(new_ids)) {
    dup <- unique(new_ids[duplicated(new_ids)])
    stop(
      "Expression sample mapping produced duplicated genotype_id values: ",
      paste(head(dup, 20), collapse = ", ")
    )
  }

  rownames(expr_df) <- new_ids
  list(expression = expr_df, audit = audit)
}

# -----------------------------------------------------------------------------
# PLINK .traw reader
# -----------------------------------------------------------------------------
resolve_traw_sample_ids <- function(raw_ids, target_ids, mode = "auto") {
  target_ids <- unique(as.character(target_ids))
  out <- rep(NA_character_, length(raw_ids))

  for (i in seq_along(raw_ids)) {
    x <- as.character(raw_ids[i])

    # 1) Exact IID match.
    if (x %in% target_ids) {
      out[i] <- x
      next
    }

    if (mode == "auto") {
      # 2) Common PLINK FID_IID form when FID == IID: IID_IID.
      repeated <- target_ids[paste0(target_ids, "_", target_ids) == x]
      if (length(repeated) == 1) {
        out[i] <- repeated
        next
      }

      # 3) General FID_IID form: use a unique target IID matching the suffix.
      suffix_hits <- target_ids[endsWith(x, paste0("_", target_ids))]
      if (length(suffix_hits) == 1) {
        out[i] <- suffix_hits
        next
      }
    }
  }

  out
}

read_traw_genotype <- function(genotype_file, snp_annot, target_samples, maf, traw_cfg) {
  hdr <- names(fread(genotype_file, nrows = 0, check.names = FALSE))
  fixed_cols <- traw_cfg$fixed_columns

  missing_fixed <- setdiff(fixed_cols, hdr)
  if (length(missing_fixed) > 0) {
    stop("PLINK .traw is missing expected columns: ", paste(missing_fixed, collapse = ", "))
  }

  raw_sample_cols <- setdiff(hdr, fixed_cols)
  mapped_ids <- resolve_traw_sample_ids(
    raw_sample_cols, target_samples,
    mode = if (!is.null(traw_cfg$sample_id_mode)) traw_cfg$sample_id_mode else "auto"
  )

  keep_sample <- !is.na(mapped_ids)
  if (!any(keep_sample)) {
    stop("No .traw sample IDs match genotype_id values from the covariate/sample-mapping file.")
  }

  selected_raw <- raw_sample_cols[keep_sample]
  selected_ids <- mapped_ids[keep_sample]

  if (anyDuplicated(selected_ids)) {
    dup <- unique(selected_ids[duplicated(selected_ids)])
    stop("Multiple .traw columns map to the same genotype_id: ", paste(dup, collapse = ", "))
  }

  cat(".traw samples   :", length(raw_sample_cols), "\n")
  cat("Matched samples :", length(selected_raw), "\n")

  traw <- fread(
    genotype_file,
    select = c(fixed_cols, selected_raw),
    check.names = FALSE,
    data.table = FALSE
  )

  required_annot <- c("SNP", "varID", "ref", "effect")
  missing_annot <- setdiff(required_annot, names(snp_annot))
  if (length(missing_annot) > 0) {
    stop("SNP annotation is missing columns required for .traw alignment: ",
         paste(missing_annot, collapse = ", "))
  }

  # Match .traw SNP IDs to annotation. Prefer annotation SNP (rsID), but also
  # allow .traw SNP to already be varID.
  idx_snp <- match(as.character(traw$SNP), as.character(snp_annot$SNP))
  idx_var <- match(as.character(traw$SNP), as.character(snp_annot$varID))
  use_idx <- idx_snp
  fallback <- is.na(use_idx) & !is.na(idx_var)
  use_idx[fallback] <- idx_var[fallback]

  keep_variant <- !is.na(use_idx)
  if (!any(keep_variant)) {
    stop("No variants in .traw matched SNP or varID in the SNP annotation.")
  }

  traw <- traw[keep_variant, , drop = FALSE]
  annot_idx <- use_idx[keep_variant]

  # Remove duplicate varIDs before transposing.
  mapped_varid <- as.character(snp_annot$varID[annot_idx])
  nondup <- !duplicated(mapped_varid)
  traw <- traw[nondup, , drop = FALSE]
  annot_idx <- annot_idx[nondup]
  mapped_varid <- mapped_varid[nondup]

  geno <- as.matrix(traw[, selected_raw, drop = FALSE])
  storage.mode(geno) <- "numeric"

  if (isTRUE(traw_cfg$align_to_effect_allele)) {
    counted <- toupper(as.character(traw$COUNTED))
    other <- toupper(as.character(traw$ALT))
    ref <- toupper(as.character(snp_annot$ref[annot_idx]))
    effect <- toupper(as.character(snp_annot$effect[annot_idx]))

    same <- counted == effect & other == ref
    flip <- counted == ref & other == effect
    allele_ok <- same | flip

    cat("Allele aligned  :", sum(allele_ok, na.rm = TRUE), "/", length(allele_ok), "variants\n")
    cat("Dosage flipped  :", sum(flip, na.rm = TRUE), "variants\n")
    cat("Allele mismatch :", sum(!allele_ok | is.na(allele_ok)), "variants dropped\n")

    allele_ok[is.na(allele_ok)] <- FALSE
    geno <- geno[allele_ok, , drop = FALSE]
    mapped_varid <- mapped_varid[allele_ok]
    flip <- flip[allele_ok]

    if (any(flip)) {
      geno[flip, ] <- 2 - geno[flip, , drop = FALSE]
    }
  }

  # samples x variants
  gt_df <- as.data.frame(t(geno), check.names = FALSE)
  rownames(gt_df) <- selected_ids
  colnames(gt_df) <- mapped_varid

  if (isTRUE(traw_cfg$drop_variants_with_missing)) {
    complete <- colSums(is.na(gt_df)) == 0
    if (sum(!complete) > 0) {
      cat("Missing GT SNPs:", sum(!complete), "variants dropped\n")
    }
    gt_df <- gt_df[, complete, drop = FALSE]
  }

  if (ncol(gt_df) == 0) stop("No genotype variants remain before MAF filtering.")

  eaf <- colMeans(gt_df, na.rm = TRUE) / 2
  maf_keep <- is.finite(eaf) & eaf >= maf & eaf <= (1 - maf)
  gt_df <- gt_df[, maf_keep, drop = FALSE]

  cat("MAF >=", maf, "   :", ncol(gt_df), "variants retained\n")
  gt_df
}

get_cis_genotype_varID_local <- function(gt_df, snp_annot, pos_col, coords, cis_window) {
  if (!pos_col %in% names(snp_annot)) stop("SNP annotation lacks position column: ", pos_col)
  snp_info <- snp_annot[
    snp_annot[[pos_col]] >= (coords[1] - cis_window) &
    snp_annot[[pos_col]] <= (coords[2] + cis_window),
    , drop = FALSE
  ]
  keep <- intersect(colnames(gt_df), as.character(snp_info$varID))
  gt_df[, keep, drop = FALSE]
}

# -----------------------------------------------------------------------------
# Genotype variant annotation normalizer
# -----------------------------------------------------------------------------
normalize_master_snp_annotation <- function(x, path) {
  canonical_cols <- c("SNP", "varID", "ref", "effect", "pos")
  variant_key_cols <- c("CHR", "POS", "ID", "REF", "ALT", "variant_key")

  if (all(canonical_cols %in% names(x))) {
    out <- x[, canonical_cols, drop = FALSE]
  } else if (all(variant_key_cols %in% names(x))) {
    # Genotype_vcf_to_traw_HTAN_GSE266546_fixed.sh writes this table directly
    # from the rsID PVAR.  Therefore REF/ALT are the VCF alleles and elastic-net
    # effect allele is defined as ALT.
    out <- data.frame(
      SNP = as.character(x$ID),
      varID = as.character(x$variant_key),
      ref = as.character(x$REF),
      effect = as.character(x$ALT),
      pos = suppressWarnings(as.numeric(x$POS)),
      stringsAsFactors = FALSE
    )
  } else {
    stop(
      "Unsupported master SNP annotation schema in ", path, ". Found columns: ",
      paste(names(x), collapse = ", "),
      ". Expected either [SNP,varID,ref,effect,pos] or ",
      "[CHR,POS,ID,REF,ALT,variant_key]."
    )
  }

  out$SNP <- trimws(as.character(out$SNP))
  out$varID <- trimws(as.character(out$varID))
  out$ref <- toupper(trimws(as.character(out$ref)))
  out$effect <- toupper(trimws(as.character(out$effect)))
  out$pos <- suppressWarnings(as.numeric(out$pos))

  valid <- !is.na(out$SNP) & nzchar(out$SNP) &
           !is.na(out$varID) & nzchar(out$varID) &
           !is.na(out$ref) & nzchar(out$ref) &
           !is.na(out$effect) & nzchar(out$effect) &
           out$ref != out$effect &
           is.finite(out$pos)

  if (any(!valid)) {
    cat("Invalid master annotation :", sum(!valid), "rows dropped\n")
    out <- out[valid, , drop = FALSE]
  }

  if (nrow(out) == 0) {
    stop("No valid variants remain in master SNP annotation: ", path)
  }

  out
}


# -----------------------------------------------------------------------------
# Cell-type-specific peak SNP filter
# -----------------------------------------------------------------------------
read_peak_rsid_filter <- function(path) {
  if (!file.exists(path)) {
    stop("Peak SNP rsID file does not exist: ", path)
  }

  # Supports BOTH forms seen from Peaks_annotate_variants_config.py:
  #   1) original one-rsID-per-line output with no header;
  #   2) later cell-type tables whose first column is RSID and may have a header.
  if (grepl("\\.gz$", path, ignore.case = TRUE)) {
    x <- fread(
      cmd = paste("zcat", shQuote(path)),
      header = FALSE,
      select = 1,
      data.table = FALSE,
      showProgress = FALSE
    )
  } else {
    x <- fread(
      path,
      header = FALSE,
      select = 1,
      data.table = FALSE,
      showProgress = FALSE
    )
  }

  if (ncol(x) < 1) {
    stop("Peak SNP rsID file has no readable column: ", path)
  }

  rsids <- tolower(trimws(as.character(x[[1]])))
  # This automatically drops a possible header value "RSID".
  rsids <- rsids[grepl("^rs[0-9]+$", rsids)]
  rsids <- unique(rsids)

  if (length(rsids) == 0) {
    stop("No valid rsIDs found in peak SNP file: ", path)
  }

  cat("Peak SNP rsIDs            :", length(rsids), "\n")
  rsids
}


# =============================================================================
# II. Model functions
# =============================================================================
do_elastic_net <- function(cis_gt, expr_adj, n_folds, cv_fold_ids, n_times, alpha) {
  # glmnet expects:
  #   x = numeric matrix, rows = samples
  #   y = plain numeric vector, length = nrow(x)
  # Make these requirements explicit so data.frame/matrix subclasses cannot
  # trigger weighted.mean length errors inside glmnet.
  x <- as.matrix(cis_gt)
  storage.mode(x) <- "double"

  y <- as.numeric(expr_adj)

  if (nrow(x) != length(y)) {
    stop(
      "Elastic-net x/y sample mismatch: nrow(x)=", nrow(x),
      ", length(y)=", length(y)
    )
  }

  if (nrow(cv_fold_ids) != length(y)) {
    stop(
      "Elastic-net fold/sample mismatch: nrow(cv_fold_ids)=",
      nrow(cv_fold_ids), ", length(y)=", length(y)
    )
  }

  if (any(!is.finite(x))) {
    stop("Elastic-net genotype matrix contains NA/NaN/Inf.")
  }
  if (any(!is.finite(y))) {
    stop("Elastic-net response contains NA/NaN/Inf.")
  }

  if (ncol(x) < 2L) {
    stop("Elastic-net requires at least 2 cis SNPs; found ", ncol(x), ".")
  }

  fold1 <- as.integer(cv_fold_ids[, 1])
  if (length(unique(fold1)) < 3L) {
    stop("Elastic-net CV requires at least 3 non-empty folds.")
  }

  # When foldid is supplied, let cv.glmnet derive the number of folds directly
  # from foldid. Do not also pass nfolds, which can become inconsistent if a
  # sampled fold label is absent.
  fit <- cv.glmnet(
    x = x,
    y = y,
    alpha = alpha,
    keep = TRUE,
    type.measure = "mse",
    foldid = fold1,
    parallel = FALSE,
    family = "gaussian"
  )

  lambda_seq <- fit$lambda
  fits <- list()
  fits[[1]] <- fit
  cvms <- matrix(NA_real_, nrow = length(lambda_seq), ncol = n_times)
  cvms[seq_along(fit$cvm), 1] <- fit$cvm

  if (n_times >= 2) {
    for (i in 2:n_times) {
      fold_i <- as.integer(cv_fold_ids[, i])

      if (length(fold_i) != length(y)) {
        stop(
          "Repeat ", i, " fold/sample mismatch: length(fold_i)=",
          length(fold_i), ", length(y)=", length(y)
        )
      }
      if (length(unique(fold_i)) < 3L) {
        stop("Repeat ", i, " has fewer than 3 non-empty CV folds.")
      }

      fit_i <- cv.glmnet(
        x = x,
        y = y,
        lambda = lambda_seq,
        alpha = alpha,
        keep = FALSE,
        type.measure = "mse",
        foldid = fold_i,
        parallel = FALSE,
        family = "gaussian"
      )

      fits[[i]] <- fit_i
      cvms[seq_along(fit_i$cvm), i] <- fit_i$cvm
    }
  }

  avg_cvm <- rowMeans(cvms, na.rm = TRUE)
  if (!any(is.finite(avg_cvm))) {
    stop("All repeated-CV MSE values are non-finite.")
  }

  best_lam_ind <- which.min(avg_cvm)
  best_lambda <- lambda_seq[best_lam_ind]

  list(
    cv_fit = fits[[1]],
    min_avg_cvm = min(avg_cvm, na.rm = TRUE),
    best_lam_ind = best_lam_ind,
    best_lambda = best_lambda
  )
}

evaluate_performance <- function(cis_gt, expr_adj, fit, best_lam_ind, best_lambda, cv_fold_ids, n_folds) {
  n_nonzero <- fit$nzero[best_lam_ind]

  if (n_nonzero > 0) {
    R2 <- rep(0, n_folds)
    for (j in 1:n_folds) {
      fold_idxs <- which(cv_fold_ids[, 1] == j)
      tss <- sum(expr_adj[fold_idxs]^2)
      rss <- sum((expr_adj[fold_idxs] - fit$fit.preval[fold_idxs, best_lam_ind])^2)
      R2[j] <- 1 - (rss / tss)
    }

    best_fit <- fit$glmnet.fit
    expr_adj_pred <- predict(best_fit, as.matrix(cis_gt), s = best_lambda)
    tss_best_fit <- sum(expr_adj^2)
    rss_best_fit <- sum((expr_adj - expr_adj_pred)^2)
    R2_mean <- mean(R2)
    R2_sd <- sd(R2)
    inR2 <- 1 - (rss_best_fit / tss_best_fit)

    weights <- best_fit$beta[which(best_fit$beta[, best_lam_ind] != 0), best_lam_ind]
    weighted_snps <- names(best_fit$beta[, best_lam_ind])[which(best_fit$beta[, best_lam_ind] != 0)]

    # Original prediction-performance calculation retained for compatibility.
    pred_perf <- summary(lm(expr_adj ~ fit$fit.preval[, best_lam_ind]))
    pred_perf_rsq <- pred_perf$r.squared
    pred_perf_pval <- pred_perf$coef[2, 4]

    y <- expr_adj
    yhat <- fit$fit.preval[, best_lam_ind]
    tss_global <- sum((y - mean(y))^2)
    rss_global <- sum((y - yhat)^2)
    R2_global <- 1 - rss_global / tss_global
    r_squared_global <- cor(y, yhat)

    list(
      weights = weights,
      n_weights = n_nonzero,
      weighted_snps = weighted_snps,
      R2_mean = R2_mean,
      R2_sd = R2_sd,
      inR2 = inR2,
      pred_perf_rsq = pred_perf_rsq,
      pred_perf_pval = pred_perf_pval,
      R2_global = R2_global,
      r_squared_global = r_squared_global
    )
  } else {
    list(
      weights = NA,
      n_weights = n_nonzero,
      weighted_snps = NA,
      R2_mean = NA,
      R2_sd = NA,
      inR2 = NA,
      pred_perf_rsq = NA,
      pred_perf_pval = NA,
      R2_global = NA,
      r_squared_global = NA
    )
  }
}

